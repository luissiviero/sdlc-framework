def run_url(env: dict[str, str] | None = None) -> str | None:
    """The workflow run's page, from the runner's own variables; None by hand."""
    env = os.environ if env is None else env
    server, repo, run_id = (
        env.get(k) for k in ("GITHUB_SERVER_URL", "GITHUB_REPOSITORY", "GITHUB_RUN_ID")
    )
    return f"{server}/{repo}/actions/runs/{run_id}" if server and repo and run_id else None


def write_park_result(
    change_dir: Path, st: status_mod.Status, check: str, reason: str, need: str, head: str | None
) -> Path:
    """``evidence/gate-f.json`` in the gate's own shape with one failed check, so the PR
    description shows the park and its "What I need from you" block (the same shape
    ``ci/run_phase.py`` writes for a park before a phase run; gate (f) overwrites it on the
    next Go)."""
    from gate.checks import CheckResult  # noqa: PLC0415
    from gate.gate import GateResult  # noqa: PLC0415

    result = GateResult(
        change_id=st.id,
        slug=st.slug,
        phase="f",
        profile=getattr(st, "profile_override", None) or "",
        human_gate=True,
        result="park",
        checks=[CheckResult(name=check, ok=False, reason=reason, need=need)],
        label=c.NEEDS_HUMAN_LABEL,
        head=head,
    )
    path = change_dir / art.EVIDENCE_DIR / art.GATE_RESULT.format(phase="f")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        json.dumps(result.as_dict(), indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
        newline="\n",
    )
    return path


def cmd_park(args) -> int:
    """The runbook job's setup step failed (an unreadable default-branch ref, a head that
    changed files outside ``changes/``, an install that exited non-zero): park the incident
    where the owner looks instead of leaving a red run - ``status.yaml: parked_reason``,
    ``evidence/gate-f.json`` with "What I need from you", the change folder committed and
    pushed on the incident branch, the Go label removed (one application is one act, as
    after a performed Go) and the intent PR refreshed with ``sdlc:needs-human``. No runbook
    runs here and no model."""
    root = Path(args.root).resolve()
    change_dir, st = _change(root, args.id)
    record, _why = finding.read(change_dir / art.EVIDENCE_DIR / finding.DETECTION_FILE)
    if st.phase != "f" or record is None:
        # the label can land on any PR (a build PR's head sdlc/<id>/c always fails the
        # setup check): only an incident at phase (f) with its detection record is parked
        _emit(
            {
                "change_id": args.id,
                "performed": False,
                "reason": f"change {args.id} is at phase {st.phase!r} with"
                f"{'' if record else 'out'} a detection record: not an incident, nothing parked",
            }
        )
        return EXIT_OK
    reason = " ".join((args.reason or "").split()) or f"the {args.check} step failed"
    url = run_url()
    if url:
        reason = f"{reason} (run: {url})"
    reason = f"{args.check}: {reason}"
    st.park(reason, phase="f")
    status_mod.write_status(change_dir, st)
    head = None
    try:
        head = gitops.run(root, "rev-parse", "HEAD").strip() or None
    except (gitops.GitError, FileNotFoundError):
        pass
    path = write_park_result(change_dir, st, args.check, reason, PARK_NEED, head)
    out: dict[str, Any] = {
        "change_id": args.id,
        "parked": reason,
        "check": args.check,
        "gate_result": str(path.relative_to(root)).replace("\\", "/"),
    }
    if args.dry_run:
        _emit(out)
        return EXIT_OK
    push = not args.no_push
    out["commit"] = _commit_change(
        root, args.id, f"maintain({args.id}): parked, the {args.check} step failed"[:500], push
    )
    if args.repo and args.pr_number:
        github = _github()
        out["label_removed"] = github.set_labels(
            args.repo, args.pr_number, [], [c.GO_LABEL], cwd=root
        )
    pr, code, err = _cli(
        PR_CLI, ["upsert", "--root", str(root), "--id", args.id, "--phase", "f"], root
    )
    out["pr"] = pr or {"error": err, "exit": code}
    _emit(out)
    # a park nobody can find is the red run this command replaces, only green: the commit
    # must be on the remote and the PR refreshed, else the job fails (session-8 review)
    commit = out["commit"]
    if not commit.get("ok") or (push and not commit.get("pushed")):
        print(f"the park was not pushed: {commit.get('reason') or commit}", file=sys.stderr)
        return EXIT_FAILED
    pr = out["pr"] or {}
    if pr.get("route") in (None, "none") and not pr.get("url"):
        print(f"no pull request carries the park: {pr.get('reason') or pr}", file=sys.stderr)
        return EXIT_FAILED
    return EXIT_OK


# --- dismiss: close with a reason (decision 25, article p.47 step 4) --------------------------
def _finding_for_dismissal(change_dir: Path) -> tuple[str, str, str, int | None] | None:
    """(kind, signature, summary, days until expiry) of the finding this change carries."""
    evidence = change_dir / art.EVIDENCE_DIR
    record, _why = finding.read(evidence / finding.DETECTION_FILE)
    if record is not None:
        summary = f"{record['metric']} at tier {record['tier']} ({record.get('rule')})"
        return "detect", record["signature"], summary, int(record.get("window_days") or 30)
    scan = evidence / "scan-finding.json"  # step 38: one scan finding per incident change
    if scan.is_file():
        try:
            data = json.loads(scan.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            return None
        sig = data.get("signature") if isinstance(data, dict) else None
        if isinstance(sig, str) and sig:
            return "scan", sig, str(data.get("summary") or ""), None
    return None


def _closing_reason(repo: str, number: int, config: dict[str, Any], root: Path):
    """The last comment by a person on the PR: (reason, login) or (None, why). ``config`` is
    the approved ``sdlc.yaml`` (``_approved_config``), whose automation identity is not a
    person; a GitHub tool's attribution footer is not part of the reason."""
    result = _github().issue_comments(repo, number, cwd=root)
    if not result.get("ok"):
        return None, None, f"could not read the comments: {result.get('reason') or 'failed'}"
    identities = automation_identity(config)
    for comment in reversed(result.get("comments") or []):
        author = str(comment.get("author") or "")
        if not author or comment.get("type") == "Bot" or BOT_RE.search(author):
            continue
        if is_automation(author, "", identities):
            continue
        text = TOOL_FOOTER_RE.sub("", "\n" + str(comment.get("body") or "").rstrip())
        body = " ".join(text.split())
        if body:
            return body, author, ""
    return None, None, "no comment by a person on the pull request: nothing dismissed"


def cmd_dismiss(args) -> int:
    root = Path(args.root).resolve()
    change_dir, st = _change(root, args.id)
    config = _config_or_empty(root)
    found = _finding_for_dismissal(change_dir)
    if found is None:
        _emit({"change_id": args.id, "dismissed": False, "reason": "no finding record"})
        return EXIT_OK
    kind, signature, summary, days = found
    reason, by = (args.reason or "").strip(), (args.by or "").strip()
    if not reason:
        if not (args.repo and args.pr_number):
            _emit({"change_id": args.id, "dismissed": False, "reason": "no --reason and no PR"})
            return EXIT_OK
        try:
            approved = _approved_config(root, config, args.repo)
        except bands_mod.BandsError as exc:
            _emit({"change_id": args.id, "dismissed": False, "reason": f"sdlc.yaml: {exc}"})
            return EXIT_OK
        reason, by_found, why = _closing_reason(args.repo, args.pr_number, approved, root)
        if not reason:
            _emit({"change_id": args.id, "dismissed": False, "reason": why})
            return EXIT_OK
        by = by or by_found or ""
    until = dismissals.until_date(days) if days else None
    out: dict[str, Any] = {
        "change_id": args.id,
        "kind": kind,
        "signature": signature,
        "reason": reason,
        "by": by,
        "until": until,
    }
    if args.dry_run:
        out["dismissed"] = False
        out["dry_run"] = True
        _emit(out)
        return EXIT_OK
    branch = DISMISS_BRANCH.format(id=args.id)
    default = _default_branch(root)
    original = None
    if gitops.is_repo(root):
        original = gitops.current_branch(root)
        if original == "HEAD":  # detached: come back to the commit
            original = gitops.run(root, "rev-parse", "HEAD").strip()
    try:
        if gitops.is_repo(root):
            start = f"origin/{default}" if gitops.has_remote(root) else default
            if gitops.has_remote(root) and _show(root, f"origin/{branch}", ".") is not None:
                start = f"origin/{branch}"  # a second close: continue the pending dismissal
            gitops.checkout_branch(root, branch, start)
        path = dismissals.path_for(root, c.CHANGES_DIR)
        store = dismissals.add(
            dismissals.load(path), signature, kind=kind, reason=reason, by=by or "owner",
            change_id=args.id, summary=summary, until=until,
        )  # fmt: skip
        dismissals.save(path, store)
        out["file"] = str(path.relative_to(root)).replace("\\", "/")
        out["dismissed"] = True
        if gitops.is_repo(root):
            title = f"dismiss({args.id}): {c.truncate_words(reason, 60)}"
            sha = gitops.commit_files(root, [out["file"]], title)
            out["commit"] = sha
            if args.open_pr and gitops.has_remote(root) and args.repo:
                gitops.push(root, branch)
                body = (
                    f"Finding {signature} ({kind}: {summary}) dismissed by {by or 'the owner'} "
                    f"on the close of pull request #{args.pr_number}: {reason}\n\n"
                    + (f"The dismissal expires on {until} (one baseline window; widen the "
                       "band in bands.yaml if the noise is the band's, p.44 step 6).\n\n"
                       if until else "")
                    + "Merging records it in changes/.dismissed.json so the same finding does "
                    "not return as new on the next run (article p.47 step 4). Nothing else "
                    "changes."
                )  # fmt: skip
                github = _github()
                out["pr"] = github.create_pr(
                    args.repo, default, branch, title, body, draft=False, cwd=root
                )
                number = (out["pr"] or {}).get("number")
                if number:  # the digest lists it under the incident label (decision 20)
                    github.ensure_label(
                        args.repo,
                        c.INCIDENT_LABEL,
                        "B60205",
                        "SDLC phase (f): an incident intent",
                        cwd=root,
                    )
                    out["label"] = github.set_labels(
                        args.repo, int(number), [c.INCIDENT_LABEL], [], cwd=root
                    )
    finally:
        if original and gitops.is_repo(root):
            try:
                gitops.run(root, "checkout", original)
            except gitops.GitError:
                pass
    _emit(out)
    return EXIT_OK


# --- CLI ----------------------------------------------------------------------------------------
def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(prog="detect", description=__doc__.split("\n\n")[0])
    sub = p.add_subparsers(dest="command", required=True)

    r = sub.add_parser("run", help="detect, log and (with --file) open the incident change")
    r.add_argument("--root", default=".")
    r.add_argument("--repo", default=None, help="owner/name (default: the GitHub origin)")
    r.add_argument("--cache", default=None, help=f"runs cache file (e.g. {DEFAULT_CACHE})")
    r.add_argument("--log", default=None, help=f"append one JSON line per run (e.g. {DEFAULT_LOG})")
    r.add_argument(
        "--force-tier",
        default="",
        choices=["", "2", "3"],
        help='rehearse the loop at tier 2 or 3; "" (the workflow\'s default) forces nothing',
    )
    r.add_argument("--file", action="store_true", help="open the incident change at tier 2/3")
    r.add_argument("--no-push", action="store_true")
    r.add_argument("--dry-run", action="store_true")

    for name in ("routes", "dispatch", "finish", "go", "park", "dismiss"):
        s = sub.add_parser(name)
        s.add_argument("--root", default=".")
        s.add_argument("--id", required=True)
        s.add_argument("--dry-run", action="store_true")
        if name != "routes":
            s.add_argument("--repo", default=None)
            s.add_argument("--no-push", action="store_true")
        if name == "dispatch":
            s.add_argument("--commit", action="store_true", help="commit the record on the branch")
        if name in ("go", "park", "dismiss"):
            s.add_argument("--pr-number", type=int, default=None)
        if name == "park":
            s.add_argument("--check", default="setup", help="the step that failed")
            s.add_argument("--reason", default="", help="its error line (the step output)")
        if name == "dismiss":
            s.add_argument("--reason", default=None, help="else the PR's last comment by a person")
            s.add_argument("--by", default=None)
            s.add_argument("--open-pr", action="store_true", help="push and open the dismissal PR")
    return p


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    # the default branch comes from $SDLC_DEFAULT_BRANCH only (gitops.default_branch): no
    # flag, so the model's session cannot point the dispatcher at a branch (decisions 11, 14)
    root = Path(args.root).resolve()
    if getattr(args, "repo", None) is None and hasattr(args, "repo"):
        try:
            args.repo = gitops.github_repo(root) if gitops.is_repo(root) else None
        except (gitops.GitError, FileNotFoundError):
            args.repo = None
    if args.command == "go" and (not args.repo or not args.pr_number):
        print("go needs --repo and --pr-number", file=sys.stderr)
        return EXIT_USAGE
    handler = {
        "run": cmd_run,
        "routes": cmd_routes,
        "dispatch": cmd_dispatch,
        "go": cmd_go,
        "park": cmd_park,
        "finish": cmd_finish,
        "dismiss": cmd_dismiss,
    }[args.command]
    try:
        return handler(args)
    except SystemExit as exc:
        if isinstance(exc.code, str):
            print(exc.code, file=sys.stderr)
            return EXIT_USAGE
        raise
    except gitops.GitError as exc:
        print(str(exc), file=sys.stderr)
        return EXIT_FAILED


if __name__ == "__main__":
    sys.exit(main())
