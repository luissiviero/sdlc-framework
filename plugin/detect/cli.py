def _act(
    root: Path,
    change_id: str,
    change_dir: Path,
    resolved: routes.Resolved,
    proposal: routes.Proposal,
    config: dict[str, Any],
    *,
    repo: str | None,
    dry_run: bool,
    authorized_by: str | None = None,
) -> dict[str, Any]:
    """Run the resolved runbook (or record that Go is needed) and write its record."""
    from detect import runbooks  # noqa: PLC0415

    name = resolved.runbook or ""
    evidence_dir = change_dir / art.EVIDENCE_DIR
    if resolved.authorization == routes.GO and not authorized_by:
        outcome = {
            "runbook": name,
            "status": "go-requested",
            "reason": "the route touches a running system (authorization: go, decision 14)",
            "args": dict(proposal.args),
            "authorization": resolved.as_dict(),
            "at": _now(),
        }
        if not dry_run:
            path = runbooks.record_path(evidence_dir, name)
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(json.dumps(outcome, indent=2, sort_keys=True) + "\n", encoding="utf-8")
        return outcome
    result = runbooks.run(
        name,
        root,
        change_id,
        dict(proposal.args),
        config=config,
        entry=resolved.project_runbook,
        incident_pr_url=_incident_pr_url(root, change_id, repo),
        repo=repo,
        timeout=_timeout(config),
        dry_run=dry_run,
    )
    outcome = result.as_dict()
    outcome["authorization"] = resolved.as_dict()
    if authorized_by:
        outcome["authorized_by"] = authorized_by
    if not dry_run:
        path = runbooks.record_path(evidence_dir, name)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(outcome, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return outcome


def _approved_ref(default: str) -> str:
    """The fully qualified remote-tracking ref of the default branch: a short
    ``origin/<default>`` resolves ``refs/tags/origin/<default>`` first (``approved_files``)."""
    return f"refs/remotes/origin/{default}"


def origin_mismatch(root: Path, expected: str | None) -> str | None:
    """Why ``origin`` is not the repository ``expected`` (``owner/name``), or None when it is
    or when nothing says which repository this is (a by-hand run without ``--repo``). The
    re-fetch of the approved copies trusts the checkout's ``origin``, and the maintain session
    that runs before ``finish`` and ``dispatch`` holds ``Bash(git *)``: a ``git remote set-url
    origin <elsewhere>`` would make the fetch bring a stranger's copies (session-7 review,
    carried; 0.2.24). ``$GITHUB_REPOSITORY`` (the runner's own variable) wins over
    ``expected``, because the CLI fills a missing ``--repo`` from the origin being checked.
    A remote URL that is not a GitHub repository at all is refused on a runner
    (``GITHUB_ACTIONS`` set: the checkout's origin is always the repository's URL there) and
    accepted anywhere else (the tests and a by-hand run push to a local bare repository).
    This closes the URL rewrite only: the session shares the whole ``.git`` (a removed remote,
    a ``git replace``, a planted hook), which ``approved_files``, ``_show`` and
    ``gitops.runner_args`` each answer for one vector — the full answer is reading the approved
    copies outside the checkout (PROGRESS session 8, known gaps)."""
    expected = (os.environ.get("GITHUB_REPOSITORY") or expected or "").strip().strip("/")
    if not expected:
        return None
    actual = gitops.github_repo(root)
    if actual is None:
        if os.environ.get("GITHUB_ACTIONS"):
            url = gitops.remote_url(root) or "(no URL)"
            return f"origin is not a GitHub repository URL on this runner: {url}"
        return None
    if actual.lower() != expected.lower():
        return f"origin is {actual}, not {expected}"
    return None


def approved_files(
    root: Path, config: dict[str, Any], repo: str | None = None
) -> tuple[dict[str, Any], Any, str]:
    """``(sdlc.yaml, bands.yaml, where from)`` as the owner approved them: the default
    branch's copies through ``git show`` when the checkout knows the remote, else the
    checkout's only when the repository has no remote at all (a by-hand run on a local
    repository); with a remote, an unreadable copy raises ``BandsError`` (fail closed). The
    maintain run holds Write and python (p.43: read-only on *source*), so an
    uncommitted edit of either file must never change a route's authorization (decision 14:
    "enforced, not remembered"; decision 11: a run cannot approve itself).

    The maintain session runs in the same checkout as the ``finish`` step and holds
    ``Bash(git *)`` (session-7 review): a short ``origin/<default>`` resolves a tag
    ``git tag origin/main <commit>`` before the remote-tracking ref (git only warns "refname
    is ambiguous"), and ``git update-ref refs/remotes/origin/main <commit>`` rewrites that ref
    locally. So the fully qualified ref (``_approved_ref``) is read, after a forced fetch of
    it from origin restores what the remote holds; a failed fetch raises ``BandsError``
    (fail closed: what the checkout has is never read). Before the fetch, ``origin`` must be
    the repository ``repo`` (else ``$GITHUB_REPOSITORY``) names (``origin_mismatch``): the
    fetch trusts the remote's URL, which the same session could have rewritten."""
    default = _default_branch(root)
    ref = _approved_ref(default)
    if not gitops.is_repo(root) or not gitops.has_remote(root):
        if os.environ.get("GITHUB_ACTIONS"):
            # a runner's checkout always has origin: a missing one was removed by the
            # session that shares the checkout (session-8 review), never a by-hand run
            raise bands_mod.BandsError(
                "the default branch's copies could not be refreshed from origin: the checkout "
                "has no origin remote on this runner"
            )
        # a by-hand run on a local repository: no remote holds an approved copy
        return config, bands_mod.load_project(root), "the checkout"
    why = origin_mismatch(root, repo)
    if why:
        raise bands_mod.BandsError(
            f"the default branch's copies could not be refreshed from origin: {why}"
        )
    try:
        gitops.run(root, "fetch", "--quiet", "origin", f"+refs/heads/{default}:{ref}")
    except (gitops.GitError, FileNotFoundError) as exc:
        raise bands_mod.BandsError(
            "the default branch's copies could not be refreshed from origin: "
            f"{ref} could not be read ({_last_line(str(exc), 1)})"
        ) from exc
    cfg_text = _show(root, ref, SDLC_FILE)
    bands_text = _show(root, ref, bands_mod.BANDS_FILE)
    if cfg_text is None or bands_text is None:
        # fail closed: never fall back to the checkout's (possibly edited) copies
        raise bands_mod.BandsError(
            f"the default branch's bands.yaml/sdlc.yaml could not be read: {ref}"
        )
    try:
        approved_cfg = status_mod.yamlish.loads(cfg_text)
    except status_mod.yamlish.YamlishError as exc:
        raise bands_mod.BandsError(f"{SDLC_FILE} at {ref}: {exc}") from exc
    if not isinstance(approved_cfg, dict):
        raise bands_mod.BandsError(f"{SDLC_FILE} at {ref}: not a mapping")
    return approved_cfg, bands_mod.load_text(bands_text), ref


def _approved_config(root: Path, config: dict[str, Any], repo: str | None = None) -> dict[str, Any]:
    """The owner's approved ``sdlc.yaml`` (``approved_files``: the default branch's copy, or
    the checkout's on a repository with no remote); raises ``BandsError`` when the remote
    copy cannot be read. ``go``, ``finish`` and ``dismiss`` decide who is a person (the
    automation identity) and run a runbook (``test_paths``, the commit identity, the timeout)
    from it: the PR head's ``sdlc.yaml`` could rename the automation identity or change
    ``test_paths``, and the Go step holds the runbook secrets (session-6 review finding,
    carried to session 7)."""
    return approved_files(root, config, repo)[0]


def _judge(
    root: Path,
    change_dir: Path,
    record: dict[str, Any],
    config: dict[str, Any],
    repo: str | None = None,
):
    proposal, why = routes.load_proposal(change_dir / art.EVIDENCE_DIR / finding.PROPOSAL_FILE)
    if proposal is None:
        return None, None, why
    try:
        config, bands, _where = approved_files(root, config, repo)
    except bands_mod.BandsError as exc:
        return proposal, None, f"bands.yaml: {exc}"
    resolved, why = routes.validate_proposal(
        proposal, int(record["tier"]), bands, config, _language(root)
    )
    # finding 3 of the session-5 review: a rehearsal never pre-approves a runbook
    routes.apply_forced(resolved, bool(record.get("forced")))
    return proposal, resolved, why


def cmd_dispatch(args) -> int:
    root = Path(args.root).resolve()
    change_dir, st = _change(root, args.id)
    record = _load_finding(change_dir)
    config = _config_or_empty(root)
    proposal, resolved, why = _judge(root, change_dir, record, config, args.repo)
    out: dict[str, Any] = {
        "change_id": args.id,
        "tier": record["tier"],
        "proposal": proposal.as_dict() if proposal else None,
    }
    if resolved is None:
        # not a failure of the run: the gate's route check parks with the same reason
        out.update({"acted": False, "reason": why})
        _emit(out)
        return EXIT_OK
    out["resolved"] = resolved.as_dict()
    if resolved.route == routes.PULL_REQUEST:
        out.update({"acted": True, "outcome": "pull_request: this intent PR is the route"})
        _emit(out)
        return EXIT_OK
    try:
        # the runbook runs with the approved sdlc.yaml (test_paths, the commit identity, the
        # timeout), never the checkout's, which the model's session could have edited
        approved = _approved_config(root, config, args.repo)
    except bands_mod.BandsError as exc:
        out.update({"acted": False, "reason": f"sdlc.yaml: {exc}"})
        _emit(out)
        return EXIT_OK
    outcome = _act(
        root, args.id, change_dir, resolved, proposal, approved,
        repo=args.repo, dry_run=args.dry_run,
    )  # fmt: skip
    out.update({"acted": outcome.get("status") == "ran", "outcome": outcome})
    if args.commit and not args.dry_run:
        out["commit"] = _commit_change(
            root, args.id, f"maintain({args.id}): route {resolved.route}", push=not args.no_push
        )
    _emit(out)
    return EXIT_OK


def _gate_and_pr(root: Path, change_id: str, push: bool, out: dict[str, Any]) -> dict[str, Any]:
    """Gate (f) on the branch, the evidence commit, the intent PR (what the maintain command
    does by hand in its steps 7 and 8)."""
    gate, code, err = _cli(
        GATE_CLI, ["check", "--root", str(root), "--id", change_id, "--phase", "f"], root
    )
    out["gate"] = gate or {"error": err, "exit": code}
    out["evidence_commit"] = _commit_change(
        root, change_id, f"maintain({change_id}): gate (f) evidence", push=push
    )
    pr, code, err = _cli(
        PR_CLI, ["upsert", "--root", str(root), "--id", change_id, "--phase", "f"], root
    )
    out["pr"] = pr or {"error": err, "exit": code}
    return out


def cmd_finish(args) -> int:
    """The deterministic tail of a CI maintain run (``sdlc-detect.yml``): the model's session
    wrote the intent and the proposal (``/sdlc-maintain <id> --diagnosis-only``); this step,
    with the project's runbook secrets in its environment and none in the model's, dispatches
    the route, runs gate (f), commits the evidence and opens the intent PR."""
    root = Path(args.root).resolve()
    change_dir, st = _change(root, args.id)
    record = _load_finding(change_dir)
    config = _config_or_empty(root)
    proposal, resolved, why = _judge(root, change_dir, record, config, args.repo)
    out: dict[str, Any] = {
        "change_id": args.id,
        "tier": record["tier"],
        "proposal": proposal.as_dict() if proposal else None,
        "dispatch": {"acted": False, "reason": why} if resolved is None else None,
    }
    push = not args.no_push
    if resolved is not None:
        out["resolved"] = resolved.as_dict()
        if resolved.route == routes.PULL_REQUEST:
            out["dispatch"] = {
                "acted": True,
                "outcome": "pull_request: this intent PR is the route",
            }
        else:
            try:
                approved = _approved_config(root, config, args.repo)
            except bands_mod.BandsError as exc:
                approved = None
                out["dispatch"] = {"acted": False, "reason": f"sdlc.yaml: {exc}"}
            if approved is not None:
                outcome = _act(
                    root, args.id, change_dir, resolved, proposal, approved,
                    repo=args.repo, dry_run=args.dry_run,
                )  # fmt: skip
                out["dispatch"] = {"acted": outcome.get("status") == "ran", "outcome": outcome}
                if not args.dry_run:
                    out["route_commit"] = _commit_change(
                        root, args.id, f"maintain({args.id}): route {resolved.route}", push=push
                    )
    if args.dry_run:
        _emit(out)
        return EXIT_OK
    _gate_and_pr(root, args.id, push, out)
    _emit(out)
    pr = out.get("pr") or {}
    if pr.get("route") in (None, "none") and not pr.get("url"):
        print(f"no pull request carries the incident: {pr.get('reason') or pr}", file=sys.stderr)
        return EXIT_FAILED
    return EXIT_OK


# --- go: the owner's per-incident authorization (decision 14) ----------------------------------
def _human_label_actor(repo: str, number: int, label: str, config: dict[str, Any]):
    found = _github().label_actor(repo, number, label)
    if not found.get("ok"):
        return None, f"could not read the label events: {found.get('reason') or 'failed'}"
    actor = found.get("actor")
    if not actor:
        return None, f"no `labeled` event for {label} on #{number}"
    if BOT_RE.search(actor) or is_automation(actor, "", automation_identity(config)):
        return None, f"{label} was applied by {actor}, not by a person: left where it is"
    return actor, ""


def cmd_go(args) -> int:
    root = Path(args.root).resolve()
    change_dir, st = _change(root, args.id)
    record = _load_finding(change_dir)
    config = _config_or_empty(root)
    try:
        # before the label's actor is judged: the head's copy could rename the automation
        # identity; unreadable, nothing runs and the label is left where it is (fail closed)
        approved = _approved_config(root, config, args.repo)
    except bands_mod.BandsError as exc:
        _emit({"change_id": args.id, "performed": False, "reason": f"sdlc.yaml: {exc}"})
        return EXIT_OK
    actor, why = _human_label_actor(args.repo, args.pr_number, c.GO_LABEL, approved)
    if actor is None:
        _emit({"change_id": args.id, "performed": False, "reason": why})
        return EXIT_OK
    proposal, resolved, why = _judge(root, change_dir, record, config, args.repo)
    if resolved is None or resolved.route == routes.PULL_REQUEST:
        _emit({"change_id": args.id, "performed": False, "reason": why or "no runbook proposed"})
        return EXIT_OK
    from detect import runbooks  # noqa: PLC0415

    record_path = runbooks.record_path(change_dir / art.EVIDENCE_DIR, resolved.runbook or "")
    try:
        recorded = json.loads(record_path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        recorded = {}
    if str((recorded or {}).get("status")) != "go-requested":
        _emit(
            {
                "change_id": args.id,
                "performed": False,
                "reason": f"runbook {resolved.runbook} did not ask for Go (record: "
                f"{(recorded or {}).get('status') or 'none'}); a Go runs a route once",
            }
        )
        return EXIT_OK
    outcome = _act(
        root, args.id, change_dir, resolved, proposal, approved,
        repo=args.repo, dry_run=args.dry_run, authorized_by=actor,
    )  # fmt: skip
    out: dict[str, Any] = {
        "change_id": args.id,
        "performed": True,
        "actor": actor,
        "route": resolved.route,
        "outcome": outcome,
    }
    if args.dry_run:
        _emit(out)
        return EXIT_OK
    st = status_mod.read_status(change_dir)
    st.runbook_authorized_by = actor
    st.touch()
    status_mod.write_status(change_dir, st)
    out["commit"] = _commit_change(
        root, args.id, f"maintain({args.id}): runbook {resolved.runbook} authorized by {actor}",
        push=not args.no_push,
    )  # fmt: skip
    github = _github()
    out["label_removed"] = github.set_labels(args.repo, args.pr_number, [], [c.GO_LABEL], cwd=root)
    _gate_and_pr(root, args.id, not args.no_push, out)
    _emit(out)
    return EXIT_OK


